# 3. REPORT
# ==============================================================================
def analyse(path):
    series, day0 = load_history(path)
    os.makedirs(OUT_DIR, exist_ok=True)
    report = {"history_file": path, "first_scan": day0.isoformat(), "zones": {}}
    print(f"Crop-health time series: {len(series)} zones, history {path}\n")
    print(f"{'Zone':6} {'Latest':>7} {'Smoothed':>9} {'Trend/day (95% CI)':>24} "
          f"{'Holt +7d':>9}  Early warning")
    for zone, s in sorted(series.items()):
        d, y = s["days"], s["health"]
        smooth = ewma(y)
        recent = d >= d[-1] - TREND_WINDOW_DAYS
        slope, lo, hi = linear_trend(d[recent], y[recent])
        model = fit_holt(d, y, s["spray_days"])
        f7 = model.predict(d[-1] + 7)
        warn_in = days_until(model, d[-1], ALERT_HEALTH_PCT, WARNING_DAYS)
        below_now = smooth[-1] < ALERT_HEALTH_PCT
        warning = ("BELOW ALERT LEVEL NOW" if below_now else
                   f"forecast below {ALERT_HEALTH_PCT:.0f}% in {warn_in} days" if warn_in else "none")
        effects = [e for e in (treatment_effect(d, y, sd) for sd in s["spray_days"]) if e]
        report["zones"][zone] = {
            "latest_pct": y[-1], "smoothed_pct": round(float(smooth[-1]), 1),
            "trend_pts_per_day": round(slope, 2), "trend_ci95": [round(lo, 2), round(hi, 2)],
            "holt_alpha": round(model.alpha, 2), "holt_beta": round(model.beta, 2),
            "holt_phi": model.phi,
            "forecast_7_days_pct": round(float(np.clip(f7, 0, 100)), 1),
            "early_warning": warning, "treatments": effects,
        }
        print(f"{zone:6} {y[-1]:6.1f}% {smooth[-1]:8.1f}% {slope:+7.2f} ({lo:+.2f} to {hi:+.2f})"
              f"{np.clip(f7, 0, 100):8.1f}%  {warning}")

    # Whole-season backtest on the zones where something happens (flat zones are trivially easy).
    print("\nForecast accuracy, rolling-origin backtest (mean absolute error, % points; lower is better):")
    report["backtest"] = {}
    totals = {m: [] for m in METHODS}
    for zone in [z for z in ("R2C2", "R2C1") if z in series]:
        s = series[zone]
        bt = backtest(s["days"], s["health"], s["spray_days"])
        report["backtest"][zone] = bt
        for h, res in bt.items():
            print(f"  {zone} {h:9}  " + "  ".join(f"{k} {v:5.2f}" for k, v in res.items()))
            for m, v in res.items():
                totals[m].append(v)
    if any(totals.values()):
        ranking = sorted(((float(np.mean(v)), m) for m, v in totals.items() if v))
        report["best_forecaster"] = {"method": ranking[0][1], "mean_mae": round(ranking[0][0], 2),
                                     "ranking": [[m, round(e, 2)] for e, m in ranking]}
        print("  Overall: " + ", ".join(f"{m} {e:.2f}" for e, m in ranking) + f"  -> best: {ranking[0][1]}")
        # A scan of n images measures the share of healthy leaves with binomial noise: the
        # average absolute error of one scan against the true value is sqrt(2/pi) * sd.
        # No forecaster can be expected to beat this by much; only more images per scan can.
        rows = [(h / 100, n) for z in report["backtest"] for h, n in zip(series[z]["health"], series[z]["n"])]
        floor = float(np.mean([np.sqrt(2 / np.pi) * np.sqrt(max(p * (1 - p), 0.0025) / n) * 100 for p, n in rows]))
        report["sampling_noise_floor_mae"] = round(floor, 2)
        print(f"  Sampling-noise floor: about {floor:.1f} points. Even a perfect forecast would score this, "
              f"because each scan of ~{int(np.mean([n for _, n in rows]))} leaf images it is checked against "
              "is itself that noisy.")

    print(f"\nEarly-warning lead time (season replayed scan by scan; review level {ALERT_HEALTH_PCT:.0f}%):")
    report["warning_lead_time"] = {}
    for zone, s in sorted(series.items()):
        lt = warning_lead_time(s["days"], s["health"], s["spray_days"])
        if lt:
            report["warning_lead_time"][zone] = lt
            when = (f"warned on day {lt['warning_day']}, {lt['lead_time_days']} days before"
                    if lt["warning_day"] is not None else "no warning before")
            print(f"  {zone}: {when} the smoothed health fell below the review level (day {lt['crossed_day']})")
    if not report["warning_lead_time"]:
        print("  No zone fell below the review level this season.")

    print(f"\nTreatment check (trend in the {TREATMENT_WINDOW_DAYS} days before vs after each spray):")
    for zone, z in sorted(report["zones"].items()):
        for e in z["treatments"]:
            verdict = ("recovering" if e["recovering"] else "NOT clearly recovering: review diagnosis and treatment")
            print(f"  {zone}: {e['slope_before_pts_per_day']:+.2f} -> {e['slope_after_pts_per_day']:+.2f} "
                  f"points/day after the spray on day {e['spray_day']}: {verdict}")

    if "R2C2" in series and "R2C1" in series:
        sp = spread_lag(series["R2C2"], series["R2C1"])
        report["spread_R2C2_to_R2C1"] = sp
        print(f"\nSpread: R2C1 follows R2C2 with a lag of about {sp['lag_days']} days "
              f"(correlation {sp['correlation']:.2f}).")

    with open(os.path.join(OUT_DIR, "time_series_report.json"), "w") as f:
        json.dump(report, f, indent=2, default=float)
    plot(series, report)
    print(f"\n[outputs] Report and charts saved in {OUT_DIR}")
    return report


def plot(series, report):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("[outputs] matplotlib not installed: skipped the charts.")
        return
    shown = [z for z in ("R2C2", "R2C1", "R0C0") if z in series] or sorted(series)[:3]
    colours = {"R2C2": "#A73F00", "R2C1": "#0072B2", "R0C0": "#0B5A43"}
    fig, ax = plt.subplots(figsize=(11, 5.5))
    for z in shown:
        s = series[z]
        c = colours.get(z, None)
        ax.scatter(s["days"], s["health"], s=14, color=c, alpha=0.45)
        ax.plot(s["days"], ewma(s["health"]), color=c, lw=2.2, label=f"{z} smoothed (EWMA)")
        m = fit_holt(s["days"], s["health"], s["spray_days"])
        resid = np.std(m.errors) if m.errors else 0
        fd = np.arange(s["days"][-1], s["days"][-1] + WARNING_DAYS + 1)
        fy = np.clip([m.predict(x) for x in fd], 0, 100)
        ax.plot(fd, fy, color=c, lw=2, ls="--")
        ax.fill_between(fd, np.clip(fy - 1.96 * resid, 0, 100), np.clip(fy + 1.96 * resid, 0, 100),
                        color=c, alpha=0.12)
        for sd in s["spray_days"]:
            ax.axvline(sd, color="#14231C", ls=":", lw=1.5)
    sprays = sorted({sd for z in shown for sd in series[z]["spray_days"]})
    if sprays:
        ax.text(sprays[0] + 0.5, 3, "spray approved", fontsize=9)
    ax.axhline(ALERT_HEALTH_PCT, color="grey", lw=1)
    ax.text(0.5, ALERT_HEALTH_PCT + 1, f"review level ({ALERT_HEALTH_PCT:.0f}% healthy)", fontsize=8, color="grey")
    ax.set_ylim(0, 102)
    ax.set_xlabel("Day of season (dots: individual scans; dashed: 7-day Holt forecast with 95% band)")
    ax.set_ylabel("% of leaf images classified Healthy")
    ax.set_title("Crop-health time series per zone (SIMULATED demo season)" if
                 "sample_scan_history" in report["history_file"] else "Crop-health time series per zone")
    ax.legend(loc="lower left")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "zone_health_trends.png"), dpi=150)
    plt.close(fig)

    bt = report.get("backtest", {})
    if bt:
        names = {"holt_damped": "Damped Holt", "naive": "Last value", "moving_avg_3": "Moving average of 3",
                 "ewma": "EWMA"}
        cols = {"holt_damped": "#0B5A43", "naive": "#9DAAA3", "moving_avg_3": "#E69F00", "ewma": "#0072B2"}
        labels = [f"{z}\n{h.replace('_', ' ')}" for z, res in bt.items() for h in res]
        x = np.arange(len(labels))
        fig, ax = plt.subplots(figsize=(9, 4.2))
        w = 0.8 / len(METHODS)
        for k, m in enumerate(METHODS):
            vals = [r[m] for res in bt.values() for r in res.values()]
            ax.bar(x - 0.4 + w / 2 + k * w, vals, w, label=names[m], color=cols[m])
        ax.set_xticks(x, labels)
        ax.set_ylabel("Mean absolute error (% points)")
        ax.set_title("Forecast backtest: lower is better")
        ax.legend()
        fig.tight_layout()
        fig.savefig(os.path.join(OUT_DIR, "forecast_backtest.png"), dpi=150)
        plt.close(fig)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--history", default=SAMPLE_PATH, help="scan-history CSV (default: the simulated sample)")
    ap.add_argument("--regenerate", action="store_true", help="rebuild the simulated sample CSV first")
    a = ap.parse_args()
    if a.regenerate or (a.history == SAMPLE_PATH and not os.path.exists(SAMPLE_PATH)):
        print(f"[data] wrote SIMULATED sample season -> {make_demo_history()}")
    analyse(a.history)


if __name__ == "__main__":
    main()
