"""
time_series_analysis.py -- crop-health time series per spraying-map zone.

WHY A TIME SERIES
--------------------------------------------------------------------------------
One scan says how a zone looks today. Repeated scans say where it is heading.
Every drone/pole scan produces, per 20 m grid zone (R0C0..R2C2, the same zones
as the spraying map and dashboard), a HEALTH INDEX: the % of that zone's leaf
images the classifier labelled Healthy. Over a season this is a time series per
zone, and this script analyses it:

  1. Smoothing      exponentially weighted moving average (EWMA), because one
                    scan of ~30 leaf images is noisy (a few images swing it).
  2. Trend          least-squares slope over the last 14 days, in percentage
                    points per day, with a 95% confidence interval.
  3. Forecast       Holt's exponential smoothing with a damped trend (level +
                    a trend that fades), its constants chosen on the zone's own
                    history. A recorded spray resets the trend, because the
                    treatment changes the zone's direction.
  4. Backtest       rolling-origin evaluation: at every point in the season,
                    forecast 1 scan and 7 days ahead using only earlier scans,
                    and compare Holt with three baselines (last value, moving
                    average, EWMA), next to the sampling-noise floor that no
                    forecaster can beat. This is how forecast accuracy is measured.
  5. Early warning  zones forecast to drop below ALERT_HEALTH_PCT within the
                    next WARNING_DAYS get flagged for an extra scan and farmer
                    review, before they cross the spraying threshold. The season
                    is replayed scan by scan to measure the warning's lead time.
  6. Treatment      intervention analysis on sprayed zones: the trend in the
                    days before the spray against the days after. A recovery
                    is evidence the treatment worked; no recovery means the
                    diagnosis or the treatment needs a second look.
  7. Spread         lagged correlation between a diseased zone and its
                    neighbours: how many days later the neighbour follows.

DATA
--------------------------------------------------------------------------------
Input is a CSV with one row per zone per scan:
    date, zone_id, n_images, n_healthy, health_index_pct, sprayed
The real system appends one row per zone after every pipeline run. The CCMT
dataset has no time dimension (single photos), so until real scans exist the
script uses data/sample_scan_history.csv: a SIMULATED season, generated by
make_demo_history() below and clearly labelled as such. Its story matches the
poster (panel 7): leaf disease starts in R2C2, spreads to R2C1, a spray is
approved in week 5, and both zones recover.

Run from the repo root:
    python model/time_series_analysis.py                  analyse the sample season
    python model/time_series_analysis.py --history my.csv analyse real scan logs
    python model/time_series_analysis.py --regenerate     rebuild the sample CSV
Outputs go to model/outputs/time_series/.
"""
import argparse
import csv
import json
import os
from datetime import date, timedelta

import numpy as np

SAMPLE_PATH = "./data/sample_scan_history.csv"
OUT_DIR = "./model/outputs/time_series"

EWMA_ALPHA = 0.4            # weight of the newest scan in the smoothed line
TREND_WINDOW_DAYS = 14      # trend = slope over the last two weeks
ALERT_HEALTH_PCT = 60.0     # starting value: below this share of healthy leaves, review the zone
WARNING_DAYS = 7            # look-ahead for the early warning
TREATMENT_WINDOW_DAYS = 21  # compare this many days (6 scans) before and after a spray


# ==============================================================================
# 1. DATA
# ==============================================================================
def make_demo_history(path=SAMPLE_PATH, seed=11):
    """SIMULATED season for demonstration: 8 weeks, a scan every 3-4 days, 9 zones.
    Each scan samples ~30 leaf images per zone; the number classified Healthy is
    binomial around a weekly 'true' health curve, so the noise is the real kind
    (few images per zone), not decoration. The R2C2 and R0C0 curves are the ones
    drawn on the poster; R2C1 is the neighbour the disease spreads to."""
    rng = np.random.default_rng(seed)
    start = date(2026, 8, 17)                        # Monday of week 1
    weekly = {                                       # true % healthy, weeks 1-8
        "R2C2": [90, 82, 70, 58, 46, 52, 64, 76],    # diseased zone (poster: red line)
        "R2C1": [93, 92, 90, 84, 76, 74, 79, 85],    # neighbour, infected later
        "R0C0": [95, 94, 95, 93, 94, 94, 93, 94],    # healthy comparison (poster: green)
    }
    for z in ("R0C1", "R0C2", "R1C0", "R1C1", "R1C2", "R2C0"):
        weekly[z] = list(np.clip(94 + rng.normal(0, 1.2, 8), 85, 99).round(1))
    spray_day = 31                                   # Thursday of week 5: farmer approves the spray
    sprayed_zones = {"R2C2", "R2C1"}
    scan_days = [d for d in range(56) if d % 7 in (0, 3)]   # Mondays and Thursdays
    mid_week = np.arange(8) * 7 + 3

    rows = []
    for zone in sorted(weekly):
        truth = np.interp(scan_days, mid_week, weekly[zone])
        for day, p in zip(scan_days, truth):
            n = int(rng.integers(26, 35))
            k = int(rng.binomial(n, p / 100))
            rows.append({"date": (start + timedelta(days=day)).isoformat(), "zone_id": zone,
                         "n_images": n, "n_healthy": k, "health_index_pct": round(100 * k / n, 1),
                         "sprayed": int(day == spray_day and zone in sprayed_zones)})
    rows.sort(key=lambda r: (r["date"], r["zone_id"]))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="") as f:
        f.write("# SIMULATED demo season (model/time_series_analysis.py make_demo_history); "
                "replace with real scan logs\n")
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    return path


def load_history(path):
    """-> {zone_id: {"days": array, "dates": [...], "health": array, "spray_days": [...]}}"""
    with open(path) as f:
        rows = list(csv.DictReader(line for line in f if not line.startswith("#")))
    day0 = min(date.fromisoformat(r["date"]) for r in rows)
    series = {}
    for r in rows:
        d = date.fromisoformat(r["date"])
        s = series.setdefault(r["zone_id"], {"days": [], "dates": [], "health": [], "n": [], "spray_days": []})
        s["days"].append((d - day0).days)
        s["dates"].append(d)
        s["health"].append(float(r["health_index_pct"]))
        s["n"].append(int(r["n_images"]))
        if int(r.get("sprayed", 0) or 0):
            s["spray_days"].append((d - day0).days)
    for s in series.values():
        order = np.argsort(s["days"])
        s["days"] = np.array(s["days"], float)[order]
        s["health"] = np.array(s["health"], float)[order]
        s["n"] = np.array(s["n"], int)[order]
        s["dates"] = [s["dates"][i] for i in order]
    return series, day0


# ==============================================================================
# 2. METHODS
# ==============================================================================
def ewma(y, alpha=EWMA_ALPHA):
    out = np.empty_like(y)
    out[0] = y[0]
    for i in range(1, len(y)):
        out[i] = alpha * y[i] + (1 - alpha) * out[i - 1]
    return out


def linear_trend(days, y):
    """OLS slope (points/day) with a 95% confidence interval."""
    x = days - days.mean()
    slope = (x * (y - y.mean())).sum() / (x ** 2).sum()
    resid = y - (y.mean() + slope * x)
    n = len(y)
    se = np.sqrt((resid ** 2).sum() / max(n - 2, 1) / (x ** 2).sum())
    t95 = {3: 12.71, 4: 4.30, 5: 3.18, 6: 2.78, 7: 2.57}.get(n, 2.45 if n < 10 else 2.2)
    return slope, slope - t95 * se, slope + t95 * se


class Holt:
    """Holt's linear exponential smoothing with a damped trend, on an irregular day axis.
    level_t = a*y_t + (1-a)*(level + trend*D(dt));  trend_t = b*(level_t - level_prev)/dt + (1-b)*phi^dt*trend
    where D(h) = phi + phi^2 + ... + phi^h, so a trend fades instead of running on forever
    (phi = 1 is the classic undamped Holt). A spray is a known intervention: it changes the
    zone's direction, so the trend is reset to zero after a spray instead of being extrapolated
    through it."""

    def __init__(self, alpha, beta, phi=1.0):
        self.alpha, self.beta, self.phi = alpha, beta, phi

    def _damp(self, h):
        return h if self.phi == 1.0 else self.phi * (1 - self.phi ** h) / (1 - self.phi)

    def fit(self, days, y, spray_days=()):
        self.level, self.trend, self.last = y[0], 0.0, days[0]
        if len(y) > 1:
            self.trend = (y[1] - y[0]) / max(days[1] - days[0], 1)
        self.errors = []
        for d, v in zip(days[1:], y[1:]):
            self.errors.append(v - self.predict(d))
            self.update(d, v)
            if d in spray_days:
                self.trend = 0.0
        return self

    def update(self, day, value):
        dt = max(day - self.last, 1)
        prev = self.level
        self.level = self.alpha * value + (1 - self.alpha) * (self.level + self.trend * self._damp(dt))
        self.trend = self.beta * (self.level - prev) / dt + (1 - self.beta) * self.phi ** dt * self.trend
        self.last = day

    def predict(self, day):
        return self.level + self.trend * self._damp(day - self.last)


def fit_holt(days, y, spray_days=()):
    """Choose alpha, beta and the damping phi by one-step-ahead squared error on the history."""
    best = None
    for phi in (0.8, 0.9, 0.95, 1.0):
        for a in np.arange(0.1, 1.0, 0.1):
            for b in np.arange(0.05, 0.65, 0.1):
                m = Holt(a, b, phi).fit(days, y, spray_days)
                sse = float(np.sum(np.square(m.errors[2:]))) if len(m.errors) > 2 else 0.0
                if best is None or sse < best[0]:
                    best = (sse, m)
    return best[1]


METHODS = ("holt_damped", "naive", "moving_avg_3", "ewma")


def forecast_with(method, days, y, spray_days, day):
    if method == "holt_damped":
        return fit_holt(days, y, spray_days).predict(day)
    if method == "naive":
        return y[-1]
    if method == "moving_avg_3":
        return y[-3:].mean()
    return ewma(y)[-1]


def backtest(days, y, spray_days=(), min_train=6):
    """Rolling origin: from every point after min_train scans, forecast the next scan and
    the scan ~7 days ahead using only earlier data (and only sprays already recorded).
    Returns the mean absolute error per method and horizon."""
    errs = {h: {m: [] for m in METHODS} for h in ("next_scan", "7_days")}
    for i in range(min_train, len(y) - 1):
        d_hist, y_hist = days[:i], y[:i]
        known_sprays = [s for s in spray_days if s <= d_hist[-1]]
        targets = {"next_scan": i}
        later = np.where(days >= days[i - 1] + 7)[0]
        if len(later):
            targets["7_days"] = later[0]
        for h, j in targets.items():
            for m in METHODS:
                errs[h][m].append(abs(y[j] - forecast_with(m, d_hist, y_hist, known_sprays, days[j])))
    return {h: {k: round(float(np.mean(v)), 2) for k, v in e.items() if v} for h, e in errs.items()}


def warning_lead_time(days, y, spray_days=(), min_train=4):
    """Replays the season scan by scan: when did the early warning first fire, and when did
    the smoothed health actually fall below the alert level? Lead time = the difference."""
    smooth = ewma(y)
    crossed = np.where(smooth < ALERT_HEALTH_PCT)[0]
    if not len(crossed):
        return None
    cross_day = days[crossed[0]]
    for i in range(min_train, crossed[0] + 1):
        m = fit_holt(days[:i], y[:i], [s for s in spray_days if s <= days[i - 1]])
        if days_until(m, days[i - 1], ALERT_HEALTH_PCT, WARNING_DAYS) is not None:
            return {"warning_day": int(days[i - 1]), "crossed_day": int(cross_day),
                    "lead_time_days": int(cross_day - days[i - 1])}
    return {"warning_day": None, "crossed_day": int(cross_day), "lead_time_days": 0}


def days_until(model, day_now, threshold, horizon):
    """First whole day within the horizon on which the forecast falls below threshold, else None."""
    for k in range(1, horizon + 1):
        if model.predict(day_now + k) < threshold:
            return k
    return None


def treatment_effect(days, y, spray_day, window=TREATMENT_WINDOW_DAYS):
    before = (days >= spray_day - window) & (days <= spray_day)
    after = (days > spray_day) & (days <= spray_day + window)
    if before.sum() < 3 or after.sum() < 3:
        return None
    s_before = linear_trend(days[before], y[before])
    s_after = linear_trend(days[after], y[after])
    return {"spray_day": int(spray_day),
            "slope_before_pts_per_day": round(s_before[0], 2),
            "slope_after_pts_per_day": round(s_after[0], 2),
            "slope_after_ci95": [round(s_after[1], 2), round(s_after[2], 2)],
            "recovering": bool(s_after[1] > 0)}       # whole CI above zero


def spread_lag(source, target, max_lag_days=21):
    """Day lag at which the target zone's health changes best follow the source zone's."""
    d0 = int(min(source["days"].min(), target["days"].min()))
    d1 = int(max(source["days"].max(), target["days"].max()))
    grid = np.arange(d0, d1 + 1)
    a = np.interp(grid, source["days"], ewma(source["health"]))
    b = np.interp(grid, target["days"], ewma(target["health"]))
    best = (0, -2.0)
    for lag in range(0, max_lag_days + 1):
        x, z = a[: len(a) - lag], b[lag:]
        if len(x) > 10 and x.std() > 0 and z.std() > 0:
            r = float(np.corrcoef(x, z)[0, 1])
            if r > best[1]:
                best = (lag, r)
    return {"lag_days": best[0], "correlation": round(best[1], 2)}


